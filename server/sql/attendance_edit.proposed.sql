-- PROPOSAL ONLY - NOT EXECUTED. Needs approval before it is run on ELOFOK.
-- Manual edit of actual times (check-in / check-out) before payroll posting.
-- Raw punches in ATT_EMP are never touched; edits live in their own table and POST_IO_EMP_PRC applies them.

-- 1) The edit itself: one row per employee per day (what the screen edits)
CREATE TABLE ATTM_IO_ADJ (
  EMP_ID      NUMBER        NOT NULL,
  IO_DATE     DATE          NOT NULL,          -- = EMP_IO_TIMES.FROM_IO_DATE (day only)
  NEW_IN      DATE,                            -- NULL = keep the punch
  NEW_OUT     DATE,                            -- NULL = keep the punch
  ORIG_IN     DATE,                            -- punch-based value when the edit was first made
  ORIG_OUT    DATE,
  REASON      VARCHAR2(500) NOT NULL,
  USER_NAME   VARCHAR2(100) NOT NULL,
  UPDATED_AT  DATE          DEFAULT SYSDATE NOT NULL,
  CONSTRAINT ATTM_IO_ADJ_PK PRIMARY KEY (EMP_ID, IO_DATE),
  CONSTRAINT ATTM_IO_ADJ_CK CHECK (NEW_IN IS NOT NULL OR NEW_OUT IS NOT NULL)
);

-- 2) Audit log: every edit / add / revert (old, new, reason, user, time)
CREATE TABLE ATTM_IO_AUDIT (
  AUDIT_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  EMP_ID      NUMBER        NOT NULL,
  IO_DATE     DATE          NOT NULL,
  ACTION      VARCHAR2(10)  NOT NULL,          -- EDIT | ADD | REVERT
  OLD_IN      DATE,  OLD_OUT DATE,
  NEW_IN      DATE,  NEW_OUT DATE,
  REASON      VARCHAR2(500),
  USER_NAME   VARCHAR2(100) NOT NULL,
  AT_TIME     DATE          DEFAULT SYSDATE NOT NULL
);
CREATE INDEX ATTM_IO_AUDIT_I1 ON ATTM_IO_AUDIT (EMP_ID, IO_DATE);

